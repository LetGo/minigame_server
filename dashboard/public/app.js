async function loadLoginLogs(offset,target){const generation=++requestGeneration;target.replaceChildren(node('p','正在加载登录记录…','loading'));try{const data=await api('login-logs',{offset});if(loggedIn&&tab==='loginLogs'&&generation===requestGeneration)renderLoginLogs(data,target);}catch(err){if(loggedIn&&tab==='loginLogs'&&generation===requestGeneration)target.replaceChildren(node('p',err.message,'error active'));}}
function renderLoginLogs(data,target){target.replaceChildren(node('p',`北京时间 ${data.today} · 共 ${data.total} 条 · 更新于 ${fmtDate(data.generatedAt)}`,'metric-detail'));const wrap=node('div',undefined,'history-table-container'),table=node('table',undefined,'history-table login-logs-table'),head=node('thead'),header=node('tr'),body=node('tbody');for(const title of ['登录时间（北京时间）','openid','昵称','首次来源场景','注册时间（北京时间）'])header.append(node('th',title));head.append(header);for(const item of data.items){const row=node('tr');row.append(node('td',fmtDate(item.loginAt)),node('td',item.openid),node('td',item.nickname||'—'),node('td',formatScene(item.sourceScene)),node('td',fmtDate(item.registeredAt)));body.append(row);}if(!data.items.length){const row=node('tr'),cell=node('td','当天暂无成功登录记录');cell.colSpan=5;row.append(cell);body.append(row);}table.append(head,body);wrap.append(table);const controls=node('div',undefined,'login-log-controls'),previous=node('button','上一页'),next=node('button','下一页');previous.type=next.type='button';previous.disabled=data.offset===0;next.disabled=!data.hasMore;previous.addEventListener('click',()=>loadLoginLogs(Math.max(0,data.offset-data.limit),target));next.addEventListener('click',()=>loadLoginLogs(data.offset+data.limit,target));controls.append(previous,node('span',`第 ${Math.floor(data.offset/data.limit)+1} 页 · 每页 ${data.limit} 条`),next);target.append(wrap,controls);}
